export default async function verifyWorkspace(page,origin) {
  const check=(condition,message)=>{if(!condition)throw new Error(message);};
  await page.goto(origin);
  await page.getByRole("button",{name:"＋ 打开文件夹 / 建立项目",exact:true}).click();
  const dialog=page.getByRole("dialog",{name:"打开文件夹",exact:true});
  await dialog.getByLabel("新文件夹名称").fill("workspace-test");
  await dialog.getByRole("button",{name:"新建文件夹",exact:true}).click();
  await dialog.getByRole("button",{name:"▸ workspace-test 打开 →",exact:true}).click();
  await dialog.getByRole("button",{name:"以此文件夹打开项目",exact:true}).click();
  const list=page.locator(".file-list");
  await list.getByText("项目说明",{exact:true}).waitFor();
  check(await list.getByText(".logos",{exact:true}).count()===0,"Internal files must start hidden");
  await page.getByLabel("显示内部文件").check();
  await list.getByText(".logos",{exact:true}).waitFor();
  await page.getByLabel("显示内部文件").uncheck();
  await page.locator('input[type=file]').first().setInputFiles({name:"input.txt",mimeType:"text/plain",buffer:Buffer.from("input-evidence")});
  await list.getByText("原始资料",{exact:true}).waitFor();
  await page.locator(".explorer-tabs").getByRole("button",{name:"方案",exact:true}).click();
  const baseline=page.locator(".study-card").filter({hasText:"默认方案"});
  await baseline.getByRole("button",{name:"编辑配置",exact:true}).click();
  const editor=page.getByRole("dialog",{name:"编辑计算方案"});
  const value=JSON.parse(await editor.getByLabel("方案 JSON 配置").inputValue());
  value.physics={type:"fluid",units:"SI"};value.solver.name="fixture";value.inputs=["assets/input.txt"];
  await editor.getByLabel("方案 JSON 配置").fill(JSON.stringify(value,null,2));
  await editor.getByRole("button",{name:"保存配置",exact:true}).click();
  await editor.waitFor({state:"hidden"});
  await baseline.getByRole("button",{name:"准备运行",exact:true}).click();
  await baseline.getByText("准备就绪",{exact:true}).waitFor();
  await baseline.getByRole("button",{name:"准备运行",exact:true}).click();
  await page.waitForFunction(()=>document.querySelectorAll(".study-run").length===2);
  await page.getByLabel("方案标识").fill("wind-10");
  await page.getByLabel("方案名称").fill("风速 10");
  await page.getByRole("button",{name:"＋ 新建方案",exact:true}).click();
  await page.locator(".study-card").getByText("风速 10",{exact:true}).waitFor();
  await page.screenshot({path:"/tmp/logos-workspace-management.png",fullPage:true});
  await baseline.getByRole("button",{name:"输入",exact:true}).first().click();
  await list.getByText("study.json",{exact:true}).waitFor();
  await list.getByText("assets",{exact:true}).click();
  await list.getByText("input.txt",{exact:true}).click();
  await page.getByText("input-evidence",{exact:true}).waitFor();
  return {passed:true,studies:2,preparedRuns:2,snapshotPreview:true};
}
