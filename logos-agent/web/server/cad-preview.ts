import { execFile } from "node:child_process";
import { promisify } from "node:util";
import { mkdtemp, readFile, rm, stat, writeFile, type FileHandle } from "node:fs/promises";
import { join, resolve } from "node:path";
import { tmpdir } from "node:os";
import { Software } from "./software.ts";
import { HttpError } from "./errors.ts";

const execute = promisify(execFile);
const inputLimit = 32 * 1024 * 1024, outputLimit = 64 * 1024 * 1024;
export type CadConverter = (input: string, output: string, signal: AbortSignal) => Promise<void>;

function validateStl(mesh: Buffer): void {
  if (mesh.length >= 84) {
    const count = mesh.readUInt32LE(80);
    if (count > 0 && count <= 1_000_000 && mesh.length === 84 + count * 50) {
      for (let face = 0; face < count; face++) {
        for (let component = 0; component < 12; component++) {
          if (!Number.isFinite(mesh.readFloatLE(84 + face * 50 + component * 4))) throw new HttpError(422, "预览网格坐标无效");
        }
      }
      return;
    }
  }
  throw new HttpError(422, "CAD 未生成完整有效的三角面网格，请下载原文件检查几何");
}

/** Preview-only tessellation: never rewrites the source CAD or the solver mesh. */
export class CadPreview {
  private readonly users = new Set<string>();
  private readonly convert: CadConverter;
  constructor(data: string, convert?: CadConverter, software = new Software(data)) {
    this.convert = convert ?? (async (input, output, signal) => {
      signal.throwIfAborted();
      const state = await software.status();
      signal.throwIfAborted();
      const gmsh = state.result?.products.find(product => product.product === "gmsh" && product.status === "installed")?.selected;
      if (!gmsh) throw new HttpError(503, "服务器未找到 Gmsh，暂不能生成 STEP 预览；仍可下载原文件");
      // Bound native CAD parsing as well as stdout: untrusted geometry can expand
      // dramatically. Linux deployment requires util-linux prlimit; never fall back unbounded.
      await execute("/usr/bin/prlimit", ["--as=2147483648", "--fsize=" + outputLimit, "--cpu=55", "--core=0", "--", gmsh, input, "-2", "-format", "stl", "-bin", "-o", output, "-nt", "1", "-v", "2", "-setnumber", "Mesh.MeshSizeFromCurvature", "12"], {
        timeout: 60_000, killSignal: "SIGKILL", maxBuffer: 256 * 1024, signal, cwd: resolve(input, ".."),
        env: { ...process.env, OPENBLAS_NUM_THREADS: "1", OMP_NUM_THREADS: "1", MKL_NUM_THREADS: "1" },
      });
    });
  }
  async render(user: string, source: FileHandle, path: string, signal: AbortSignal): Promise<Buffer> {
    if (!/\.(step|stp)$/i.test(path)) throw new HttpError(415, "当前 CAD 预览仅支持 STEP/STP");
    if (this.users.has(user) || this.users.size >= 2) throw new HttpError(429, "CAD 预览正在转换，请稍后重试");
    this.users.add(user);
    let directory: string | undefined;
    try {
      signal.throwIfAborted();
      const size = (await source.stat()).size;
      if (!size) throw new HttpError(415, "STEP 文件为空，请重新生成后再下载或预览");
      if (size > inputLimit) throw new HttpError(413, "STEP 超过 32 MiB 预览限制，请下载原文件");
      // Read only the pinned descriptor, never a caller-supplied absolute filesystem path.
      const buffer = Buffer.alloc(size + 1);
      let length = 0;
      while (length < buffer.length) {
        const read = await source.read(buffer, length, buffer.length - length, length);
        if (!read.bytesRead) break;
        length += read.bytesRead;
      }
      if (length !== size) throw new HttpError(409, "文件仍在写入，请等待生成结束后重试");
      if (!/^\s*ISO-10303-21\s*;/i.test(buffer.subarray(0, Math.min(length, 256)).toString("ascii")) || !/END-ISO-10303-21\s*;\s*$/i.test(buffer.subarray(Math.max(0, length - 256), length).toString("ascii"))) {
        throw new HttpError(415, "STEP 文件头或结束标记无效，可能未生成完整；请检查生成日志");
      }
      directory = await mkdtemp(join(tmpdir(), "logos-cad-preview-"));
      const input = join(directory, "input.step"), output = join(directory, "preview.stl");
      await writeFile(input, buffer.subarray(0, length), { mode: 0o600 });
      await this.convert(input, output, signal);
      signal.throwIfAborted();
      const result = await stat(output);
      if (!result.isFile() || result.size < 15) throw new HttpError(422, "CAD 没有可显示的表面，请检查几何完整性");
      if (result.size > outputLimit) throw new HttpError(413, "预览网格过大，请下载 STEP 在 CAD 软件中打开");
      const mesh = await readFile(output);
      validateStl(mesh);
      return mesh;
    } catch (error) {
      if (error instanceof HttpError) throw error;
      if (signal.aborted) throw new HttpError(499, "预览已取消");
      throw new HttpError(422, "STEP 转换失败或超时，请下载原文件检查几何；源文件未修改");
    } finally {
      this.users.delete(user);
      // directory is generated by mkdtemp under the OS temporary directory, never user input.
      if (directory) await rm(directory, { recursive: true, force: true });
    }
  }
}
